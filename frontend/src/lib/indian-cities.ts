export function resolveIndianCity(value: string): string | undefined {
  const normalizedValue = value.trim().toLocaleLowerCase('en-IN');
  return INDIAN_CITIES.find((city) => city.toLocaleLowerCase('en-IN') === normalizedValue)
    ?? Object.entries(INDIAN_CITY_ALIASES).find(([alias]) => alias.toLocaleLowerCase('en-IN') === normalizedValue)?.[1];
}
